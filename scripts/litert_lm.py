def find_include_dir():
	candidates = [
		os.environ.get("LITERT_LM_ROOT", "") + "/include",
		"/opt/litert-lm/include",
		os.path.join(ROOT, "external", "litert-lm", "include"),
	]
	for c in candidates:
		if c and os.path.isdir(os.path.join(c, "c")):
			return c
	return None


def parse_param(p, idx):
	p = p.strip()
	m = re.search(r"(\w+)\s*$", p)
	if m:
		pname = m.group(1)
		ptype = p[:m.start()].strip()
		if not ptype:
			ptype = pname
			pname = f"arg{idx}"
		return ptype, pname
	return p, f"arg{idx}"


def discover_functions():
	inc_dir = find_include_dir()
	if not inc_dir:
		print("Warning: LiteRT-LM include directory not found, unable to parse headers.", file=sys.stderr)
		return []

	funcs = []
	seen = set()
	for hf in HEADER_FILES:
		full_path = os.path.join(inc_dir, "c", hf)
		if not os.path.exists(full_path):
			continue
		with open(full_path, "r", encoding="utf-8") as f:
			content = f.read()
		content = re.sub(r"//.*", "", content)
		content = re.sub(r"/\*.*?\*/", "", content, flags=re.DOTALL)
		for m in re.finditer(r"LITERT_LM_C_API_EXPORT\s*(?:LITERT_LM_C_API_DEPRECATED\([^)]*\)\s*)?([^;]+?\b(litert_lm_\w+)\s*\(([^)]*)\)\s*;)", content, re.DOTALL):
			ret_type = m.group(1).split(m.group(2))[0].strip()
			name = m.group(2)
			raw_params = m.group(3).strip()
			if name in seen:
				continue
			seen.add(name)
			params = []
			if raw_params and raw_params != "void":
				for idx, p in enumerate(raw_params.split(",")):
					ptype, pname = parse_param(p, idx)
					params.append((ptype, pname))
			funcs.append({
				"name": name,
				"short_name": name[len("litert_lm_"):],
				"ret_type": ret_type,
				"params": params,
				"raw_params": raw_params,
				"tracked": name in TRACKED_COMMANDS,
			})
	return funcs


