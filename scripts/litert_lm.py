			output.write(f'extern "C" EXPORT {f["ret_type"]} {f["name"]}({param_decl})\n{{\n')
			output.write("\tlava_writer& instance = lava_writer::instance();\n")
			output.write("\tlitert_lm_layer_runtime_state& state = instance.litert_lm_layer;\n")
			output.write("\tensure_litert_lm_dispatch(state);\n")
			output.write("\tlitert_lm_call_guard guard(state);\n")
			output.write(f'\tif (!state.target_dispatch.{f["short_name"]})\n\t{{\n')
			output.write(f'\t\tABORT("LiteRT-LM symbol %s not found in underlying library", "{f["name"]}");\n\t}}\n')
			if f["ret_type"] == "void":
				output.write(f'\tstate.target_dispatch.{f["short_name"]}({param_call});\n')
			else:
				output.write(f'\treturn state.target_dispatch.{f["short_name"]}({param_call});\n')
			output.write("}\n\n")


