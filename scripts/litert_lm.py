def write_passthrough(funcs):
	with open(PASSTHROUGH_PATH, "w", encoding="utf-8") as output:
		output.write("// This file contains only code auto-generated by litert_lm.py\n\n")
		output.write("#include \"write.h\"\n")
		output.write("#include \"litert_lm_auto.h\"\n\n")

		passthrough_funcs = [f for f in funcs if not f["tracked"]]
		for f in passthrough_funcs:
			param_decl = ", ".join(f"{pt} {pn}" for pt, pn in f["params"]) if f["params"] else ("void" if f["raw_params"] == "void" else "")
