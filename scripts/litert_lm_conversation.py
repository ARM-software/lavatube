"""Generate the synchronous conversation subset using the installed C signatures.

Conversation packets contain a JSON parameter object. Handle values are tracked
indices, never native pointers; null arguments remain distinct from null handles.
"""

import os


HANDLES = {
    "LiteRtLmEngine": ("engine", "engine"),
    "LiteRtLmSessionConfig": ("session_config", "session_config"),
    "LiteRtLmConversationConfig": ("conversation_config", "conversation_config"),
    "LiteRtLmConversationOptionalArgs": ("conversation_optional_args", "conversation_optional_args"),
    "LiteRtLmConversation": ("conversation", "conversation"),
    "LiteRtLmJsonResponse": ("json_response", "json_response"),
}

COMMANDS = [
    "conversation_config_create", "conversation_config_delete",
    "conversation_config_set_session_config",
    "conversation_config_set_system_message", "conversation_config_set_messages",
    "conversation_config_set_tools", "conversation_config_set_extra_context",
    "conversation_config_set_prompt_template",
    "conversation_config_set_enable_constrained_decoding",
    "conversation_config_set_constraint_provider",
    "conversation_optional_args_create", "conversation_optional_args_delete",
    "conversation_optional_args_set_max_output_tokens",
    "conversation_optional_args_set_constraint",
    "conversation_create", "conversation_delete", "conversation_clone",
    "conversation_send_message", "json_response_get_string",
    "json_response_delete",
]


def handle_type(pt):
    return pt.replace("const", "").replace("*", "").strip()


def generate(root, funcs):
    files = {}
    for part in ("write", "read", "replay", "print"):
        files[part] = ["// This file contains only code auto-generated by litert_lm_conversation.py\n"]
    for f in funcs:
        short = f["short_name"]
        if short not in COMMANDS:
            continue
        name = f["name"]
        enum = "LITERT_LM_" + name
        params = f["params"]
        status = f["ret_type"] != "void"
        deleting = short.endswith("_delete")
        getter = short == "json_response_get_string"
        w = files["write"]
        r = files["replay"]
        w += [f'extern "C" EXPORT {f["ret_type"]} {name}({f["raw_params"]})\n{{',
              "\tlava_writer& instance = lava_writer::instance();",
              "\tlitert_lm_layer_runtime_state& state = instance.litert_lm_layer;",
              "\tensure_litert_lm_dispatch(state);",
              f'\tif (!state.target_dispatch.{short}) ABORT("Missing LiteRT-LM symbol: {name}");',
              f"\tlava_file_writer& writer = begin_litert_lm_packet(instance, state, {enum});"]
        if status:
            w += ["\tLiteRtLmStatusCode result;"]
        w += ["\t{", "\t\tlitert_lm_call_guard guard(state);"]
        call = f'state.target_dispatch.{short}({", ".join(pn for _, pn in params)});'
        w += ["\t\t" + ("result = " if status else "") + call, "\t}",
              "\tJson::Value parameters(Json::objectValue);", "\t{", "\t\tlava::lock_guard lock(frame_mutex);"]
        r += [f"case {enum}:", "{", "\tconst Json::Value& p = packet.conversation_parameters;",
              f'\tif (!state->dispatch.{short}) ABORT("Missing LiteRT-LM symbol: {name}");']
        args = []
        outputs = []
        for pt, pn in params:
            ht = handle_type(pt)
            value = f'p["{pn}"]'
            dest = f'parameters["{pn}"]'
            if ht in HANDLES:
                stem, destructor = HANDLES[ht]
                if "**" in pt:
                    outputs.append((ht, pn, stem, destructor))
                    w += [f"\t\tuint32_t {pn}_index = {pn} ? CONTAINER_NULL_VALUE : CONTAINER_INVALID_INDEX;",
                          f"\t\tif (result == 0 && {pn} && *{pn})", "\t\t{",
                          f"\t\t\ttrackable* data = state.{stem}_index.add(*{pn}, writer.current);",
                          "\t\t\tdata->enter_created();", f"\t\t\t{pn}_index = data->index;", "\t\t}",
                          f"\t\t{dest} = {pn} ? Json::Value({pn}_index) : Json::nullValue;"]
                    r += [f"\t{ht}* {pn} = nullptr;"]
                    args.append(f"{value}.isNull() ? nullptr : &{pn}")
                else:
                    lookup = "destroy_litert_lm_handle" if deleting else "lookup_litert_lm_index"
                    w += [f"\t\t{dest} = {lookup}(state.{stem}_index, const_cast<{ht}*>({pn}), writer.current);"]
                    args.append(f"litert_lm_replay_handle(state->{stem}_map, {value})")
            elif "char" in pt:
                if "**" in pt:
                    w += [f'\t\tparameters["{pn}_present"] = {pn} != nullptr;',
                          f"\t\t{dest} = (result == 0 && {pn} && *{pn}) ? Json::Value(*{pn}) : Json::nullValue;"]
                    r += [f"\tconst char* {pn} = nullptr;"]
                    args.append(f'p["{pn}_present"].asBool() ? &{pn} : nullptr')
                else:
                    w += [f"\t\t{dest} = {pn} ? Json::Value({pn}) : Json::nullValue;"]
                    args.append(f"{value}.isNull() ? nullptr : {value}.asCString()")
            else:
                w += [f"\t\t{dest} = {pn};"]
                conv = "asBool" if pt == "bool" else "asInt"
                args.append(f"static_cast<{pt}>({value}.{conv}())")
        w += ["\t}"]
        if status:
            w += ['\tparameters["result"] = static_cast<int32_t>(result);']
        w += ["\tJson::FastWriter json_writer;", "\twriter.write_string(json_writer.write(parameters).c_str());",
              "\twriter.end_packet();"]
        if status:
            w += ["\treturn result;"]
        w += ["}\n"]

        if short == "conversation_send_message":
            r += ['\tif (!p["out_response"].isNull()) state->json_response_conversations[p["out_response"].asUInt()] = p["conversation"].asUInt();']
        if short == "conversation_delete":
            r += ['\tLiteRtLmConversation* conversation = litert_lm_replay_handle(state->conversation_map, p["conversation"]);',
                  '\tif (conversation) state->collect_statistics(p["conversation"].asUInt(), nullptr, conversation);']
        call = f'state->dispatch.{short}({", ".join(args)});'
        r += ["\t" + ("replay_status = " if status else "") + call]
        for ht, pn, stem, destructor in outputs:
            value = f'p["{pn}"]'
            r += [f"\tif (*replay_status == 0 && {pn})", "\t{",
                  f"\t\tif (!{value}.isNull() && {value}.asUInt() < CONTAINER_NULL_VALUE)", "\t\t{",
                  f"\t\t\tstate->{stem}_map[{value}.asUInt()] = {pn};", "\t\t}", "\t\telse", "\t\t{",
                  f"\t\t\tstate->dispatch.{destructor}_delete({pn});", "\t\t}", "\t}"]
        if deleting:
            pt, pn = params[0]
            stem = HANDLES[handle_type(pt)][0]
            r += [f'\tstate->{stem}_map.erase(p["{pn}"].asUInt());']
        if getter:
            r += ['\tstate->record_output(reader, replay_status, out_json);',
                  '\tif (parent->litert_verify_output && packet.result == 0 && (packet.pointer_flags & 2))', "\t{",
                  '\t\tif (*replay_status == 0 && out_json) state->verify_text(reader, out_json);',
                  '\t\telse state->verification_unavailable++;', "\t}"]
        # Match the session replay policy for unexpected creation/inference errors.
        if status and (outputs or short == "conversation_send_message"):
            r += [f'\tif (*replay_status != 0 && packet.result == 0 && !parent->litert_verify_output) ABORT("{name} failed with status %d", int(*replay_status));']
        r += ["\tbreak;", "}"]
        files["read"] += [f"case {enum}:"]
        files["print"] += [f"case {enum}:"]
    files["read"] += ["{", "\tJson::Reader json_reader;", "\tconst char* json = read_string();",
                      '\tif (!json || !json_reader.parse(json, packet.conversation_parameters)) ABORT("Invalid LiteRT-LM conversation packet");',
                      '\tpacket.has_result = packet.conversation_parameters.isMember("result");',
                      '\tif (packet.has_result) packet.result = packet.conversation_parameters["result"].asInt();',
                      '\tif (apicall == LITERT_LM_litert_lm_json_response_get_string)', "\t{",
                      '\t\tpacket.pointer_flags = packet.conversation_parameters["out_json_present"].asBool() ? 2 : 0;',
                      '\t\tpacket.response_text = packet.conversation_parameters["out_json"].isNull() ? "" : packet.conversation_parameters["out_json"].asString();',
                      "\t}", "\tbreak;", "}"]
    files["print"] += ["\tparams = litert_lm.conversation_parameters;", "\tbreak;"]
    for part, lines in files.items():
        with open(os.path.join(root, "generated", f"litert_lm_conversation_{part}.inc"), "w") as out:
            out.write("\n".join(lines) + "\n")
